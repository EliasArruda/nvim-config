local M = {}

function M.setup()
	local dap = require("dap")

	-- 🐹 GO (Delve)
	dap.adapters.go = {
		type = "server",
		port = "${port}",
		executable = {
			command = vim.fn.stdpath("data") .. "/mason/bin/dlv",
			args = { "dap", "-l", "127.0.0.1:${port}" },
		},
	}

	dap.configurations.go = {
		{
			name = "Debug (current package)",
			type = "go",
			request = "launch",
			program = "${fileDirname}",
			cwd = "${workspaceFolder}",
			showRegisters = false,
		},
		{
			name = "Debug (package tests)",
			type = "go",
			request = "launch",
			mode = "test",
			program = "${fileDirname}",
			cwd = "${workspaceFolder}",
		},
		{
			name = "Debug (main module)",
			type = "go",
			request = "launch",
			program = "${workspaceFolder}",
			cwd = "${workspaceFolder}",
		},
		{
			name = "Attach (running process)",
			type = "go",
			request = "attach",
			mode = "local",
			processId = require("dap.utils").pick_process,
		},
	}

	dap.adapters.codelldb = {
		type = "server",
		port = "${port}",
		executable = {
			command = vim.fn.stdpath("data") .. "/mason/packages/codelldb/extension/adapter/codelldb",
			args = { "--port", "${port}" },
		},
	}
	for _, language in ipairs({ "c", "cpp" }) do
		dap.configurations[language] = {
			setmetatable({
				name = "Build and debug (C/C++)",
				type = "codelldb",
				request = "launch",
				program = function()
					return require("config.cpp-debug").program()
				end,
				stopOnEntry = false,
				preRunCommands = { "breakpoint set --name main --one-shot true" },
			}, {
				__call = function(config)
					-- Resolve the context before DAP evaluates asynchronous options.
					local resolved = setmetatable(vim.deepcopy(config), nil)
					resolved.cwd = resolved.cwd or require("core.project").root()
					if type(resolved.program) == "function" then
						resolved.program = resolved.program()
					end
					return resolved
				end,
			}),
			{
				name = "Launch executable (C/C++)",
				type = "codelldb",
				request = "launch",
				program = function()
					return vim.fn.input("Executable: ", require("core.project").root() .. "/build/", "file")
				end,
				cwd = function()
					return require("core.project").root()
				end,
				stopOnEntry = false,
			},
			{
				name = "Attach to process (C/C++)",
				type = "codelldb",
				request = "attach",
				pid = require("dap.utils").pick_process,
				cwd = function()
					return require("core.project").root()
				end,
			},
		}
	end

	-- Rust debug targets are generated by rustaceanvim from Cargo metadata.
	-- C# debug targets and launch profiles are managed by easy-dotnet.nvim.
end

return M
